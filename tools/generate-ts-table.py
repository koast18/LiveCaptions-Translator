#!/usr/bin/env python3
"""生成 src/Core/Text/TraditionalToSimplifiedTable.cs。

数据来自 OpenCC 的 data/dictionary/TSCharacters.txt（Apache-2.0，
https://github.com/BYVoid/OpenCC）。本仓库同样是 Apache-2.0，因此可以内嵌这张表；
保留本脚本是为了让这张表可以重新生成、便于升级。

    python tools/generate-ts-table.py

表以「每两个码位一对」的形式打包成一个字符串常量，运行时按 Rune 解析，
这样非 BMP 汉字（代理对）也能正确参与映射。
"""

from __future__ import annotations

import urllib.request

SOURCE = "https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TSCharacters.txt"
TARGET = "src/Core/Text/TraditionalToSimplifiedTable.cs"

HEADER = """// <auto-generated>
// 由 tools/generate-ts-table.py 从 OpenCC 的 data/dictionary/TSCharacters.txt 生成。
// OpenCC 采用 Apache-2.0 许可（https://github.com/BYVoid/OpenCC），本项目同为 Apache-2.0。
// 表中每两个码位构成一对「繁体 → 简体」；非 BMP 字符用代理对表示，因此按 Rune 解析。
// </auto-generated>

namespace LiveCaptionsTranslator.Core.Text
{
    /// <summary>
    /// Character level Traditional to Simplified mapping. This is a one-to-one character
    /// conversion, not a phrase aware one: it converts 個→个, 說→说 and so on, but it does not
    /// rewrite regional vocabulary (電腦 stays 电脑, not 计算机).
    /// </summary>
    internal static class TraditionalToSimplifiedTable
    {
        /// <summary>Number of entries in the packed table.</summary>
        public const int PairCount = %d;

        /// <summary>The packed 繁简 pairs, two code points per entry.</summary>
        public const string Packed =
"""


def fetch_pairs() -> list[tuple[str, str]]:
    request = urllib.request.Request(SOURCE, headers={"User-Agent": "LiveCaptions-Translator"})
    text = urllib.request.urlopen(request, timeout=60).read().decode("utf-8")

    pairs: list[tuple[str, str]] = []
    for line in text.split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        parts = line.split("\t")
        if len(parts) < 2:
            continue

        traditional = parts[0].strip()
        # OpenCC lists alternative simplifications separated by spaces; take the first.
        simplified = parts[1].strip().split(" ")[0].strip()

        # The C# table works code point by code point.
        if len(traditional) != 1 or len(simplified) != 1 or traditional == simplified:
            continue

        pairs.append((traditional, simplified))

    return pairs


def main() -> None:
    pairs = fetch_pairs()
    packed = "".join(traditional + simplified for traditional, simplified in pairs)

    assert '"' not in packed and "\\" not in packed, "packed table must be a plain C# string literal"

    lines = [packed[i : i + 76] for i in range(0, len(packed), 76)]
    body = "\n".join(
        '            "%s"%s' % (line, ";" if index == len(lines) - 1 else "")
        for index, line in enumerate(lines)
    )

    with open(TARGET, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(HEADER % len(pairs) + body + "\n    }\n}\n")

    print(f"wrote {TARGET}: {len(pairs)} pairs")


if __name__ == "__main__":
    main()
